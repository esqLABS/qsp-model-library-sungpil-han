KIC_NIL   : 0.6    : Intracellular accumulation rate constant (h^-1)
KOUT_NIL  : 0.35   : Intracellular efflux (h^-1)
EC50_NIL  : 0.02   : IC50 nilotinib (uM, ~20x more potent than imatinib; PD reads intracellular)
EMAX_NIL  : 0.93   : Maximum effect
GAMMA_NIL : 1.15   : Hill coefficient

// --- Asciminib (ASC) PK Parameters (ASCEMBL, OPTIC trials) -- [was ka_asc/F_asc/Vd_asc/CL_asc/IC50_asc/IC50_asc_r/Emax_asc/Emax_asc_r/Hill_asc]
// 40 mg BID standard; 200 mg BID for T315I
KA_ASC        : 1.2    : Absorption rate (h^-1)
F_ASC         : 0.72   : Bioavailability (~72%)
V1_ASC        : 95.0   : Volume of distribution (L)
CL_ASC        : 7.5    : Total clearance (L/h), t1/2~8.7h
EC50_ASC      : 0.0005 : IC50 asciminib vs sensitive/WT BCR-ABL (uM, 0.5 nM, very potent STAMP); PD reads plasma directly (no intracellular compartment in the original)
EMAX_ASC      : 0.90   : Maximum effect (sensitive)
GAMMA_ASC     : 1.3    : Hill coefficient (sensitive)
EC50_ASC_T315I: 0.004  : IC50 asciminib vs T315I resistant clone (200mg BID needed, uM)
EMAX_ASC_T315I: 0.82   : Maximum effect vs T315I
GAMMA_ASC_T315I: 1.3   : Hill coefficient (T315I) -- same numeric value as GAMMA_ASC; the original used one shared Hill_asc for both effect terms, split here into two independently-named parameters per compound-effect pair, values unchanged

// --- Tumor suppression / competition ---
Kcomp : 1e-9     : Competition coefficient (density dependence)
K_total : 1e12   : Carrying capacity (total cells in marrow)

// --- Drug switches (0=off, 1=on) ---
