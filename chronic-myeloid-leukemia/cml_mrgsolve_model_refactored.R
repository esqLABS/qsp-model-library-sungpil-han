NK_imt_effect : 0.3 : Imatinib immune restoration (% NK increase)

$INIT @annotated
// Steady-state normal hematopoiesis (Michor 2005 calibrated)
y0  : 1e4    : HSC (normal hematopoietic stem cells) initial count
y1  : 5e4    : CMP (common myeloid progenitor, normal) initial count
y2  : 4e5    : GMP (granulocyte-macrophage progenitor, normal) initial count
y3  : 4e9    : Neutrophils_normal (mature blood cells) initial count (4e9/L x ~1L BM equivalent)
// CML at diagnosis (CP phase): ~10^12 leukemic cells total
x0q : 1e4    : LSC_quiescent (BCR-ABL+ quiescent, TKI-refractory) at diagnosis
x0p : 2e3    : LSC_cycling (BCR-ABL+ proliferating, TKI-sensitive) at diagnosis
x1  : 1e7    : LPC1 (leukemic progenitor committed) at diagnosis
x2  : 5e7    : LPC2 (leukemic progenitor differentiated) at diagnosis
x3  : 5e10   : WBC_leukemic (mature CML cells / blasts) at diagnosis (WBC ~80e9/L)
xs  : 8e3    : LSC_sensitive (TKI-sensitive, BCR-ABL WT), majority at diagnosis
xsp : 8e6    : LPC_sensitive (sensitive progenitors)
xr  : 10     : LSC_resistant (T315I/resistant LSC), rare at diagnosis (~10 cells)
xrp : 100    : LPC_resistant (resistant progenitors)
// Imatinib (IMT) PK -- all zero at t=0 [was Gut_imt/Cp_imt/Cic_imt]
GUT_IMT  : 0 : Imatinib gut depot
CENT_IMT : 0 : Imatinib plasma concentration (uM) -- state IS the concentration by construction, see PK note in refactor notes
IC_IMT   : 0 : Imatinib intracellular concentration (uM) -- PD-facing (bespoke biophase compartment)
// Dasatinib (DAS) PK -- all zero at t=0 [was Cp_das/Cic_das]
CENT_DAS : 0 : Dasatinib plasma concentration (uM), no depot (continuous-rate input, see PK note)
IC_DAS   : 0 : Dasatinib intracellular concentration (uM) -- PD-facing (bespoke biophase compartment)
// Nilotinib (NIL) PK -- all zero at t=0 [was Gut_nil/Cp_nil/Cic_nil]
GUT_NIL  : 0 : Nilotinib gut depot
CENT_NIL : 0 : Nilotinib plasma concentration (uM)
IC_NIL   : 0 : Nilotinib intracellular concentration (uM) -- PD-facing (bespoke biophase compartment)
// Asciminib (ASC) PK -- all zero at t=0 [was Gut_asc/Cp_asc]
GUT_ASC  : 0 : Asciminib gut depot
CENT_ASC : 0 : Asciminib plasma concentration (uM) -- PD-facing directly (no intracellular compartment in the original)

$ODE
// ============================================================
// Helper: MW conversions for dose (mg) -> umol
// Imatinib MW = 493.6 g/mol; Dasatinib = 488.0; Nilotinib = 529.5; Asciminib = 449.5
// Dose entered as mg/day; rate into gut = Dose/24 mg/h (continuous infusion approx)
// ============================================================

double dose_rate_imt = dose_imt / 24.0 / 493.6 * 1000.0;  // umol/h
double dose_rate_das = dose_das / 24.0 / 488.0 * 1000.0;
double dose_rate_nil = dose_nil / 24.0 / 529.5 * 1000.0;
double dose_rate_asc = dose_asc / 24.0 / 449.5 * 1000.0;

// ============================================================
// PK ODEs -- one clearly-delimited block per compound
// ============================================================

// --- Imatinib (IMT) PK: Archetype 3 (depot + central, linear) plus a
// bespoke intracellular biophase compartment (IC_IMT) that only receives
// from CENT_IMT (no back-flux) and is what PD actually reads. ---
dxdt_GUT_IMT  = F_IMT * dose_rate_imt - KA_IMT * GUT_IMT;
dxdt_CENT_IMT = KA_IMT * GUT_IMT / V1_IMT - (CL_IMT / V1_IMT) * CENT_IMT;
dxdt_IC_IMT   = KIN_IMT * CENT_IMT - KOUT_IMT * IC_IMT;

// --- Dasatinib (DAS) PK: no depot -- continuous zero-order infusion
// approximation straight into CENT_DAS (edge case in the guide: preserved
// exactly as the original modeled it), plus the same bespoke intracellular
// biophase pattern as IMT/NIL. ---
dxdt_CENT_DAS = F_DAS * dose_rate_das / V1_DAS - (CL_DAS / V1_DAS) * CENT_DAS;
dxdt_IC_DAS   = KIC_DAS * CENT_DAS - KOUT_DAS * IC_DAS;

// --- Nilotinib (NIL) PK: Archetype 3 (depot + central, linear) plus the
// same bespoke intracellular biophase compartment as IMT. ---
dxdt_GUT_NIL  = F_NIL * dose_rate_nil - KA_NIL * GUT_NIL;
dxdt_CENT_NIL = KA_NIL * GUT_NIL / V1_NIL - (CL_NIL / V1_NIL) * CENT_NIL;
dxdt_IC_NIL   = KIC_NIL * CENT_NIL - KOUT_NIL * IC_NIL;

// --- Asciminib (ASC) PK: Archetype 3 (depot + central, linear), no
// peripheral, no intracellular compartment -- PD reads plasma directly. ---
dxdt_GUT_ASC  = F_ASC * dose_rate_asc - KA_ASC * GUT_ASC;
dxdt_CENT_ASC = KA_ASC * GUT_ASC / V1_ASC - (CL_ASC / V1_ASC) * CENT_ASC;

// ============================================================
// Exposed concentrations (C_<STEM>) and Hill effect interface (EFFECT_<STEM>)
// PD: Drug Effect Functions (Emax model, Hill equation)
// Effect = fraction of BCR-ABL-driven proliferation inhibited
// ============================================================

// Imatinib: PD reads the INTRACELLULAR concentration (genuinely distinct
// tissue site from plasma, per the guide's two-concentration carve-out) --
// the original's own E_imt read Cic_imt, never Cp_imt.
double C_IMT = (IC_IMT > 0) ? IC_IMT : 0;
double EFFECT_IMT = EMAX_IMT * pow(C_IMT, GAMMA_IMT) /
                    (pow(EC50_IMT, GAMMA_IMT) + pow(C_IMT, GAMMA_IMT));

// Dasatinib: PD reads the intracellular concentration, same as imatinib.
double C_DAS = (IC_DAS > 0) ? IC_DAS : 0;
double EFFECT_DAS = EMAX_DAS * pow(C_DAS, GAMMA_DAS) /
                    (pow(EC50_DAS, GAMMA_DAS) + pow(C_DAS, GAMMA_DAS));

// Nilotinib: PD reads the intracellular concentration, same as imatinib.
double C_NIL = (IC_NIL > 0) ? IC_NIL : 0;
double EFFECT_NIL = EMAX_NIL * pow(C_NIL, GAMMA_NIL) /
                    (pow(EC50_NIL, GAMMA_NIL) + pow(C_NIL, GAMMA_NIL));

// Asciminib: PD reads plasma directly (40 mg BID dose regimen; sensitive cells).
double C_ASC = (CENT_ASC > 0) ? CENT_ASC : 0;
double EFFECT_ASC = EMAX_ASC * pow(C_ASC, GAMMA_ASC) /
                    (pow(EC50_ASC, GAMMA_ASC) + pow(C_ASC, GAMMA_ASC));

// Asciminib effect on T315I resistant cells (200 mg BID -- higher IC50);
// same C_ASC concentration, independent Hill parameters for the resistant target.
double EFFECT_ASC_T315I = EMAX_ASC_T315I * pow(C_ASC, GAMMA_ASC_T315I) /
                    (pow(EC50_ASC_T315I, GAMMA_ASC_T315I) + pow(C_ASC, GAMMA_ASC_T315I));

// Combined TKI effect (additive, capped at 0.98) -- combined only at the
// point the disease equations actually use them, exactly as the original did.
double E_total_sens = fmin(0.98, EFFECT_IMT + EFFECT_DAS + EFFECT_NIL + EFFECT_ASC);
double E_total_res  = fmin(0.98, EFFECT_ASC_T315I);  // Only asciminib (high dose) hits T315I

// ============================================================
// Density-dependent competition (Lotka-Volterra type)
// ============================================================
double Ntotal = x0q + x0p + x1 + x2 + x3 + xs + xsp + xr + xrp +
                y0 + y1 + y2 + y3;
double suppress = fmax(0.0, 1.0 - Kcomp * Ntotal);

// ============================================================
// Normal Hematopoiesis ODEs
// ============================================================
// y0: HSC — self-renewal + input - differentiation - death
dxdt_y0 = ay0 * y0 + suppress * 0.0 - by0 * y0 - dy0 * y0;
dxdt_y1 = c1 * by0 * y0 - by1 * y1 - dy1 * y1;
dxdt_y2 = c2 * by1 * y1 - by2 * y2 - dy2 * y2;
dxdt_y3 = c3 * by2 * y2 - dy3 * y3;

// ============================================================
// Leukemic Hierarchy ODEs (total CML pool: xs+xr tracking separately)
// ============================================================

// LSC quiescent: activated by TKI pressure -> quiescence; killed by NK
double q_in  = q_dorm * x0p;   // cycling->quiescent (increases under TKI)
double q_out = q_act  * x0q;   // quiescent->cycling
double NK_kill_x0q = kNK_kill * NK_base * x0q / (x0q + 1e3);

dxdt_x0q = q_in - q_out - d0 * x0q - NK_kill_x0q;

// LSC cycling: self-renewal + activation - quiescence - differentiation - death - TKI kill - NK
double TKI_kill_x0p = E_total_sens * x0p;
double NK_kill_x0p  = kNK_kill * NK_base * x0p / (x0p + 1e3);

dxdt_x0p = a0 * x0p + q_out - q_in - b0 * x0p - d0 * x0p
           - TKI_kill_x0p - NK_kill_x0p + mu * a0 * xs;  // mutation from xs

// LPC1
double TKI_kill_x1 = E_total_sens * x1 * 0.6;  // progenitors less sensitive
dxdt_x1 = lc1 * b0 * x0p - b1 * x1 - d1 * x1 - TKI_kill_x1;

// LPC2
double TKI_kill_x2 = E_total_sens * x2 * 0.8;
dxdt_x2 = lc2 * b1 * x1 - b2 * x2 - d2 * x2 - TKI_kill_x2;

// Leukemic WBC/blasts
double TKI_kill_x3 = E_total_sens * x3 * 1.0;  // most sensitive (post-mitotic)
double NK_kill_x3  = kNK_kill * NK_base * x3 / (x3 + 1e8);
double CTL_kill_x3 = kCTL_kill * CTL_base * x3 / (x3 + 1e8);

dxdt_x3 = lc3 * b2 * x2 - d3 * x3 - TKI_kill_x3 - NK_kill_x3 - CTL_kill_x3;

// ============================================================
// Sensitive Clone ODEs
// ============================================================
double TKI_kill_xs = E_total_sens * xs;
dxdt_xs  = as0 * xs - bs0 * xs - ds0 * xs - TKI_kill_xs - mu * as0 * xs;
dxdt_xsp = lc1 * bs0 * xs + asp * xsp - dsp * xsp - E_total_sens * xsp * 0.7;

// ============================================================
// Resistant Clone (T315I) ODEs
// ============================================================
double TKI_kill_xr  = E_total_res * xr;   // only asciminib 200mg hits this
double TKI_kill_xrp = E_total_res * xrp * 0.7;

dxdt_xr  = ar0 * xr - br0 * xr - dr0 * xr - TKI_kill_xr;
dxdt_xrp = lc1 * br0 * xr + arp * xrp - drp * xrp - TKI_kill_xrp;

$TABLE
// BCR-ABL IS% calculation
// IS% = CML cells / (CML + normal cells) x 100
// Approximate: total CML WBC / (total CML WBC + normal neutrophils)

double CML_total  = x3 + xrp + xsp;
double Norm_total = y3;
// NOTE: renamed to *_calc (build-compat fix, see refactor notes) -- BCRPCT,
// LOG_IS, Resist_frac are also bare names in $CAPTURE below, and mrgsolve
// 2.0.1 auto-promotes every bare "double NAME = ..." in $TABLE to a
// reportable member, which then collides with the same name's own
// "capture NAME = ...;" line ("redefinition of capture ...", confirmed via
// qspserver /model_manifest on the untouched original). Purely a local
// variable rename; the reported BCRPCT/LOG_IS/Resist_frac values and every
// formula that reads them are numerically identical to the original.
double BCRPCT_calc = 100.0 * CML_total / fmax(CML_total + Norm_total, 1.0);

// Log10 BCR-ABL IS
double LOG_IS_calc = (BCRPCT_calc > 0.0001) ? log10(BCRPCT_calc) : -5.0;

// Molecular response milestones
double CHR_reached  = (BCRPCT_calc < 10.0)      ? 1.0 : 0.0;
double MMR_reached  = (BCRPCT_calc < 0.1)       ? 1.0 : 0.0;
double MR4_reached  = (BCRPCT_calc < 0.01)      ? 1.0 : 0.0;
double MR45_reached = (BCRPCT_calc < 0.0032)    ? 1.0 : 0.0;

// WBC count (10^9/L, assuming 5L blood volume)
double WBC_total_blood = (x3 + Norm_total) / 5e9;  // cells/L / (cells/count unit)

// PK summary (informational only, plasma sum across all 4 TKIs; not read by any PD equation)
double Cp_active = CENT_IMT + CENT_DAS + CENT_NIL + CENT_ASC;

// Resistant fraction
double Resist_frac_calc = (xr + xrp) / fmax(CML_total, 1.0);

capture BCRPCT     = BCRPCT_calc;
capture LOG_IS     = LOG_IS_calc;
capture CHR        = CHR_reached;
capture MMR        = MMR_reached;
capture MR4        = MR4_reached;
capture MR45       = MR45_reached;
capture WBC        = WBC_total_blood;
capture LSC_total  = x0q + x0p + xs + xr;
capture LSC_quies  = x0q / fmax(x0q + x0p, 1.0);  // quiescent fraction
capture Resist_frac = Resist_frac_calc;

$CAPTURE BCRPCT LOG_IS CHR MMR MR4 MR45 WBC LSC_total LSC_quies
         Resist_frac C_IMT C_DAS C_NIL C_ASC
         EFFECT_IMT EFFECT_DAS EFFECT_NIL EFFECT_ASC EFFECT_ASC_T315I
'

# ============================================================
# Compile model
# ============================================================
mod <- mcode("cml_qsp_refactored", cml_code)
cat("Model compiled successfully. Compartments:", length(mod@cmts), "\n")
cat("Parameters:", length(param(mod)), "\n")

# ============================================================
# SIMULATION SCENARIOS
# ============================================================

# Common simulation time: 10 years = 87,600 hours
t_end_yr  <- 10        # years
t_end_hr  <- t_end_yr * 365.25 * 24  # hours
dt        <- 24        # output every 24h (daily)

times <- seq(0, t_end_hr, by = dt)
# Convert to months for display
to_months <- function(t_hr) t_hr / (365.25 * 24 / 12)

#-----------------------------------------------------------------
# SCENARIO 1: Untreated CML progression (CP -> potential AP/BC)
#-----------------------------------------------------------------
cat("\n--- Scenario 1: Untreated CML ---\n")

scen1 <- mod %>%
  param(dose_imt = 0, dose_das = 0, dose_nil = 0, dose_asc = 0) %>%
  mrgsim(end = t_end_hr, delta = dt) %>%
  as.data.frame() %>%
  mutate(scenario = "Untreated", time_months = to_months(time))

cat("Final BCR-ABL IS% (untreated, 10yr):", tail(scen1$BCRPCT, 1), "%\n")

#-----------------------------------------------------------------
# SCENARIO 2: Imatinib 400 mg/day (IRIS trial — standard of care 2001)
#-----------------------------------------------------------------
cat("\n--- Scenario 2: Imatinib 400mg/day (IRIS) ---\n")

scen2 <- mod %>%
  param(dose_imt = 400, dose_das = 0, dose_nil = 0, dose_asc = 0) %>%
  mrgsim(end = t_end_hr, delta = dt) %>%
  as.data.frame() %>%
  mutate(scenario = "Imatinib 400mg/day", time_months = to_months(time))

# Check IRIS-calibrated milestones:
# CHR @ 3mo: ~95%; CCyR @ 12mo: ~73%; MMR @ 18mo: ~39%
mmr_3mo  <- scen2$MMR[scen2$time_months >= 3][1]
mmr_12mo <- scen2$MMR[scen2$time_months >= 12][1]
mmr_18mo <- scen2$MMR[scen2$time_months >= 18][1]
cat("MMR achieved @ 3mo:", mmr_3mo, "| 12mo:", mmr_12mo, "| 18mo:", mmr_18mo, "\n")
cat("BCR-ABL IS% @ 12mo:", round(scen2$BCRPCT[scen2$time_months >= 12][1], 3), "%\n")

#-----------------------------------------------------------------
# SCENARIO 3: Dasatinib 100 mg/day (DASISION trial)
# Faster and deeper responses vs imatinib
#-----------------------------------------------------------------
