F_DAS     : 0.24   : Bioavailability (14-34%)
V1_DAS    : 2505.0 : Volume of distribution (L), highly distributed
CL_DAS    : 220.0  : Total clearance (L/h), t1/2~5-6h
KIC_DAS   : 0.8    : Intracellular accumulation rate constant (h^-1)
KOUT_DAS  : 0.4    : Intracellular efflux (h^-1)
EC50_DAS  : 0.025  : IC50 dasatinib (uM, ~10x more potent than imatinib; PD reads intracellular)
