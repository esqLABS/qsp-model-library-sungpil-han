dose_das : 0  : Dasatinib dose (mg/day)
dose_nil : 0  : Nilotinib dose (mg/day, BID; specify daily total)
dose_asc : 0  : Asciminib dose (mg/day, BID; specify daily total)

// --- Immune parameters ---
kNK_kill : 0.001 : NK cell kill rate of leukemic cells
kCTL_kill: 0.0005 : CTL kill rate of leukemic cells
NK_base  : 1e8   : Baseline NK cell count
