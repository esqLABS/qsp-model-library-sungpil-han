server <- function(input, output, session) {

  observeEvent(input$preset, {
    p <- switch(input$preset,
      "microadenoma (F)"          = list(ns0=0.35, d2rs=0.50, sex="female", fgen=1.0,
                                         fdrive=1.0, stalkp=1, apab=0, ap_drug="none"),
      "macroadenoma (F)"          = list(ns0=3.20, d2rs=0.35, sex="female", fgen=1.0,
                                         fdrive=1.0, stalkp=1, apab=0, ap_drug="none"),
      "giant, male"               = list(ns0=18.0, d2rs=0.25, sex="male", fgen=1.0,
                                         fdrive=1.3, stalkp=1, apab=0, ap_drug="none"),
      "partial resistance"        = list(ns0=3.20, d2rs=0.15, sex="female", fgen=1.0,
                                         fdrive=1.0, stalkp=1, apab=0, ap_drug="none"),
      "true resistance (AIP-like)"= list(ns0=3.20, d2rs=0.04, sex="male", fgen=1.3,
                                         fdrive=1.0, stalkp=1, apab=0, ap_drug="none"),
      "stalk effect (NFPA)"       = list(ns0=0.001, d2rs=0.50, sex="female", fgen=1.0,
                                         fdrive=1.0, stalkp=0.05, apab=0, ap_drug="none"),
      "macroprolactinaemia"       = list(ns0=0.001, d2rs=0.50, sex="female", fgen=1.0,
                                         fdrive=1.0, stalkp=1, apab=2.2, ap_drug="none"),
      "antipsychotic-induced"     = list(ns0=0.001, d2rs=0.50, sex="female", fgen=1.0,
                                         fdrive=1.0, stalkp=1, apab=0,
                                         ap_drug="risperidone-like"),
      "healthy control"           = list(ns0=0.001, d2rs=0.50, sex="female", fgen=1.0,
                                         fdrive=1.0, stalkp=1, apab=0, ap_drug="none"))
    updateSliderInput(session, "ns0", value = p$ns0)
    updateSliderInput(session, "d2rs", value = p$d2rs)
    updateSliderInput(session, "fgen", value = p$fgen)
    updateSliderInput(session, "fdrive", value = p$fdrive)
    updateSliderInput(session, "stalkp", value = p$stalkp)
    updateSliderInput(session, "apab", value = p$apab)
    updateRadioButtons(session, "sex", selected = p$sex)
    updateSelectInput(session, "ap_drug", selected = p$ap_drug)
  })

  sim <- reactive({ simulate(reactiveValuesToList(input)) })

  # ---- tab 1 --------------------------------------------------------------
  output$tbl_profile <- renderDT({
    d <- sim()
    tt <- c(PRESIM, PRESIM + 365, max(d$time))
    lab <- c("At diagnosis", "After 1 year", sprintf("After %.0f years", (max(d$time)-PRESIM)/365))
    vars <- c(PRLB="Biological prolactin (ng/mL)", PRLMEAS_="Reported prolactin (ng/mL)",
              PEGREC="PEG recovery (%)", TVOL_="Tumour volume (mL)",
              CELLN="Tumour cell mass (mL)", VCELL="Mean cell volume",
              COMPR_="Optic chiasm compression (cm)", VFMD="Visual field MD (dB)",
              OVF="Ovulatory capacity", TST="Testosterone (ng/dL)", E2G="Oestradiol (pg/mL)",
              TSCORE="Lumbar T-score", PFRACT="Vertebral fracture probability (%)",
              BW="Body weight (kg)", IR="HOMA-IR", CORT="Cortisol reserve",
              SIGDRIVE="D2 signalling drive", PTR="Moderate-or-worse TR probability (%)",
              PICD="Impulse-control disorder probability (%)")
    m <- sapply(tt, function(t) sapply(names(vars), function(v) atd(d, v, t)))
    df <- data.frame(metric = unname(vars), round(m, 3), check.names = FALSE)
    names(df) <- c("Metric", lab)
    datatable(df, rownames = FALSE, options = list(pageLength = 20, dom = "t"))
  })

  output$p_profile <- renderPlot({
    d <- sim()
    dd <- d %>% select(year, PRLB, PRLMEAS_, TVOL_, VFMD, TSCORE, OVF) %>%
      pivot_longer(-year)
    lv <- c(PRLB="Biological PRL", PRLMEAS_="Reported PRL", TVOL_="Tumour volume mL",
            VFMD="Visual field MD dB", TSCORE="Lumbar T-score", OVF="Ovulatory capacity")
    dd$name <- factor(lv[dd$name], levels = lv)
    ggplot(dd, aes(year, value)) +
      geom_line(colour = PAL[1], linewidth = 0.9) +
      facet_wrap(~name, scales = "free_y", ncol = 3) + pres_line() +
      labs(x = "Years (0 = tumour seeding)", y = NULL,
           title = "The whole course of the generated phenotype",
           subtitle = "Dashed line = the point at which the patient presents and treatment begins") +
      theme_prl()
  })

  # ---- tab 2 --------------------------------------------------------------
  output$txt_occ <- renderText({
    d <- sim(); r <- d[which.min(abs(d$time - max(d$time))), ]
    p <- build_par(reactiveValuesToList(input))
    paste0(
      "SIGDRIVE = SUM_i e_i (C_i/K_i) / (1 + SUM_j C_j/K_j)   x   D2R density\n\n",
      sprintf("  Healthy dopamine-only SIGDRIVE                        : %.4f\n", 0.0909),
      sprintf("  Current SIGDRIVE (after all ligands compete)          : %.4f  (%.2fx)\n",
              r$SIGDRIVE, r$SIGDRIVE/0.0909),
      sprintf("  Tumour-clone active receptor signal SIGS              : %.4f\n", r$SIGS),
      sprintf("  Residual transcription (branch 2, lower = suppressed) : %.4f\n", r$RTRS),
      sprintf("  Residual secretory-granule release (branch 1)         : %.4f\n", r$REXS),
      "\n  The four directions the same equation produces:\n",
      "    Agonist           -> SIGDRIVE rises -> prolactin falls\n",
      "    D2 antagonist     -> an e=0 ligand displaces dopamine -> prolactin rises\n",
      "    Aripiprazole      -> e=0.25, high affinity -> alone it exceeds physiological tone\n",
      "    Stalk compression -> the delivery (DAP) term is cut -> only normal cells are disinhibited (a ceiling exists)\n")
  })

  output$p_occ <- renderPlot({
    d <- sim()
    dd <- d %>% select(year, SIGDRIVE, SIGS, DAP) %>% pivot_longer(-year)
    lv <- c(SIGDRIVE="SIGDRIVE (total D2 drive)", SIGS="SIGS (tumour active receptors)",
            DAP="Portal dopamine (nM)")
    dd$name <- factor(lv[dd$name], levels = lv)
    ggplot(dd, aes(year, value, colour = name)) + geom_line(linewidth = 0.9) +
      facet_wrap(~name, scales = "free_y") + scale_colour_manual(values = PAL) +
      pres_line() + guides(colour = "none") +
      labs(x = "Years", y = NULL, title = "Occupancy and delivery",
           subtitle = "Portal dopamine rises through the short loop — the deliverer is normal, the receptor is the problem") +
      theme_prl()
  })

  output$p_branch <- renderPlot({
    d <- sim(); r0 <- d[which.min(abs(d$time - PRESIM)), ]
    dd <- d %>% filter(time >= PRESIM) %>%
      transmute(day = time - PRESIM,
                `branch 1 exocytosis` = REXS/r0$REXS,
                `branch 2 transcription` = RTRS/r0$RTRS,
                `branch 3 cell volume` = VCELL/r0$VCELL,
                `branch 4 cell number` = CELLN/r0$CELLN,
                `prolactin` = PRLB/r0$PRLB) %>%
      pivot_longer(-day)
    ggplot(dd, aes(day + 1, value, colour = name)) + geom_line(linewidth = 0.9) +
      scale_x_log10() + scale_colour_manual(values = PAL) +
      labs(x = "Days after treatment start + 1 (log)", y = "Ratio to the value at diagnosis",
           title = "One receptor, four clocks",
           subtitle = "Secretion and transcription settle within days, cell volume takes two months, cell number takes years") +
      theme_prl()
  })

  # ---- tab 3 --------------------------------------------------------------
  output$p_pk <- renderPlot({
    d <- sim() %>% filter(time >= PRESIM)
    dd <- d %>% transmute(day = time - PRESIM,
                          `Plasma cabergoline (nM)` = CABNM,
                          `Pituitary biophase (nM)` = CAB_E,
                          `Plasma bromocriptine (nM)` = BRC_C/10700*1e6/654.6,
                          `Plasma quinagolide (nM)` = QUI_C/1200*1e6/395.6) %>%
      pivot_longer(-day) %>% filter(value > 1e-9)
    if (!nrow(dd)) return(NULL)
    ggplot(dd, aes(day, value, colour = name)) + geom_line(linewidth = 0.8) +
      scale_colour_manual(values = PAL) +
      labs(x = "Days after treatment start", y = "Concentration (nM)",
           title = "Why once weekly is enough",
           subtitle = "The biophase sits at about 60x the plasma concentration with a ~4 day half-life, so it is close to an infusion") +
      theme_prl()
  })

  output$txt_pk <- renderText({
    d <- sim() %>% filter(time > max(time) - 28)
    sprintf(paste0("  Plasma cabergoline, last 4 weeks    mean %.4f nM (= %.1f pg/mL)\n",
                   "  Biophase, last 4 weeks              mean %.3f nM (%.1fx the D2 Ki of 0.70 nM)\n",
                   "  Biophase peak/trough ratio          %.2f\n",
                   "  5-HT2B occupancy (plasma-driven)    mean %.4f\n",
                   "  D3 occupancy (plasma-driven)        mean %.4f\n"),
            mean(d$CABNM), mean(d$CABNM)*451.6, mean(d$CAB_E),
            mean(d$CAB_E)/0.7,
            ifelse(min(d$CAB_E) > 0, max(d$CAB_E)/min(d$CAB_E), NA),
            mean(d$OCC5HT), mean(d$OCCD3))
  })

  # ---- tab 4 --------------------------------------------------------------
  output$p_prl <- renderPlot({
    d <- sim()
    dd <- d %>% transmute(year,
                          `Biological (monomer)` = PRLB,
                          `Immunoreactive analyte` = PRLIMM,
                          `Reported value (assay)` = PRLMEAS_,
                          `After 1:100 dilution` = PRLDIL) %>% pivot_longer(-year)
    ggplot(dd, aes(year, value, colour = name)) + geom_line(linewidth = 0.9) +
      scale_y_log10() + scale_colour_manual(values = PAL) + pres_line() +
      geom_hline(yintercept = 25, linetype = "33", colour = "grey50") +
      labs(x = "Years", y = "Prolactin (ng/mL, log)",
           title = "Four different prolactins",
           subtitle = "The gaps between the curves are the hook effect (reported value falls) and macroprolactin (it rises)") +
      theme_prl()
  })

  output$p_hook <- renderPlot({
    a <- 10^seq(1, 5, length.out = 300)
    dd <- data.frame(analyte = a,
                     `Reported_value` = a/(1 + (a/4000)^4),
