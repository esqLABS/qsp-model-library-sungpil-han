build_par <- function(i) {
  p <- list(
    NS0     = i$ns0,
    NR0     = i$nr0,
    D2RS0   = i$d2rs,
    D2RR0   = 0.05,
    FDRIVE  = i$fdrive,
    FGEN    = i$fgen,
    SEX     = ifelse(i$sex == "male", 1, 0),
    STALKP  = i$stalkp,
    APABSET = i$apab,
    PRIMHYP = i$primhyp,
    FCLR    = i$fclr,
    MGMT0   = i$mgmt,
    FTREPL  = i$ftrepl,
    KI_5HT2B= i$ki5ht,
    ICDSUSC = i$icdsusc
  )
  if (i$preg) p$PREGON <- PRESIM + i$pregday
  if (i$surg) { p$SURGD <- PRESIM + i$surgday
                p$SURGRES <- i$surgres; p$SURGHYP <- i$surghyp }
  if (i$ap_drug == "aripiprazole") {
    p$EFF_AP <- 0.25; p$KI_AP <- 0.34; p$FU_AP <- 0.01
    p$CL_AP  <- 210;  p$V_AP  <- 1400
  } else if (i$ap_drug == "quetiapine (sparing)") {
    p$EFF_AP <- 0.00; p$KI_AP <- 45.0
  }
  p
}

build_ev <- function(i, end) {
  ee <- list()
  wk <- max(1, ceiling((end - PRESIM - i$startday)/7))
  if (i$da == "cabergoline" && i$cabdose > 0) {
    ii <- if (i$cabsplit) 3.5 else 7
    amt <- if (i$cabsplit) i$cabdose/2 else i$cabdose
    nd  <- max(1, ceiling((end - PRESIM - i$startday)/ii))
    stopd <- if (i$stopyr > 0) PRESIM + i$startday + i$stopyr*365 else Inf
    nd  <- min(nd, max(1, ceiling((stopd - PRESIM - i$startday)/ii)))
    ee[[length(ee)+1]] <- ev(time = PRESIM + i$startday, amt = amt,
                             cmt = "CAB_G", ii = ii, addl = nd - 1)
  }
  if (i$da == "bromocriptine" && i$brcdose > 0)
    ee[[length(ee)+1]] <- ev(time = PRESIM + i$startday, amt = i$brcdose/3,
                             cmt = "BRC_G", ii = 1/3,
                             addl = 3*max(1, end - PRESIM - i$startday) - 1)
  if (i$da == "quinagolide" && i$quidose > 0)
    ee[[length(ee)+1]] <- ev(time = PRESIM + i$startday, amt = i$quidose/1000,
                             cmt = "QUI_G", ii = 1,
                             addl = max(1, end - PRESIM - i$startday) - 1)
  if (i$ap_drug != "none" && i$apdose > 0)
    ee[[length(ee)+1]] <- ev(time = PRESIM, amt = i$apdose, cmt = "AP_G",
                             ii = 1, addl = max(1, end - PRESIM) - 1)
  if (i$tmz)
    for (k in 0:(i$tmzcyc - 1))
      ee[[length(ee)+1]] <- ev(time = PRESIM + i$tmzstart + 28*k,
                               amt = 180*1.8, cmt = "TMZ_C", ii = 1, addl = 4)
  if (!length(ee)) return(NULL)
  ds <- lapply(ee, as.data.frame)
  cn <- unique(unlist(lapply(ds, names)))
  ds <- lapply(ds, function(d) { for (k in setdiff(cn, names(d))) d[[k]] <- 0; d[cn] })
  as.ev(do.call(rbind, ds))
}

simulate <- function(i) {
  end <- PRESIM + i$horizon*365
  e   <- build_ev(i, end)
  m   <- param(mod, build_par(i))
  out <- if (is.null(e)) mrgsim(m, end = end, delta = 1, maxsteps = 500000, hmax = 0.5)
         else mrgsim(m, events = e, end = end, delta = 1, maxsteps = 500000, hmax = 0.5)
  d <- as.data.frame(out)
  d$year <- d$time/365
  d
}

atd  <- function(d, v, t) d[[v]][which.min(abs(d$time - t))]
prs  <- function(d, v) atd(d, v, PRESIM)

